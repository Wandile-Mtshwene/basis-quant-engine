"""Bundle the Python engine into the Next.js app for Vercel serverless deploy.

Vercel builds the `web/` directory in isolation, so the engine source and its
FastAPI wrapper are copied next to the serverless entrypoint (web/api/index.py)
and a runtime requirements.txt is written.  Re-run this before every deploy.

    uv run python scripts/vendor_web.py
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB_API = ROOT / "web" / "api"

RUNTIME_REQUIREMENTS = [
    "fastapi",
    "pydantic",
    "numpy",
    "pandas",
]


def main() -> None:
    WEB_API.mkdir(parents=True, exist_ok=True)

    # 1. vendor the engine package (including the real table CSVs under data/)
    dst_basis = WEB_API / "basis"
    if dst_basis.exists():
        shutil.rmtree(dst_basis)
    shutil.copytree(ROOT / "src" / "basis", dst_basis)

    # 2. vendor the FastAPI app as _app.py
    shutil.copy2(ROOT / "api" / "main.py", WEB_API / "_app.py")

    # 3. write requirements for the Vercel Python runtime
    (ROOT / "web" / "requirements.txt").write_text("\n".join(RUNTIME_REQUIREMENTS) + "\n")

    # 4. serverless entrypoint that exposes the ASGI app
    (WEB_API / "index.py").write_text(
        '"""Vercel Python serverless entrypoint. Exposes the FastAPI ASGI app.\n'
        'Generated by scripts/vendor_web.py - do not edit by hand."""\n'
        "import os\nimport sys\n\n"
        "sys.path.insert(0, os.path.dirname(__file__))\n\n"
        "from _app import app  # noqa: E402\n\n"
        "__all__ = [\"app\"]\n"
    )

    print("Vendored engine ->", WEB_API)
    print("Wrote web/requirements.txt and web/api/index.py")


if __name__ == "__main__":
    main()
